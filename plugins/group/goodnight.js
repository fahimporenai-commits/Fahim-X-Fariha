function getSocket(message) {
  return message?.client || message?.conn || message?.sock || null;
}

async function sendTextMessage(message, text, quoted = null) {
  const chatId = message?.from || message?.key?.remoteJid;
  const sock = getSocket(message);

  if (typeof message?.send === "function") {
    try {
      if (quoted) {
        await message.send(text, { quoted });
      } else {
        await message.send(text);
      }
      return;
    } catch (_) {}
  }

  if (sock && typeof sock.sendMessage === "function" && chatId) {
    await sock.sendMessage(
      chatId,
      { text },
      quoted ? { quoted } : {}
    );
  }
}

async function closeGroupChat(message) {
  const groupJid = message?.from || message?.key?.remoteJid;
  const sock = getSocket(message);

  if (typeof message?.groupSettingUpdate === "function") {
    await message.groupSettingUpdate(groupJid, "announcement");
    return true;
  }

  if (sock && typeof sock.groupSettingUpdate === "function" && groupJid) {
    await sock.groupSettingUpdate(groupJid, "announcement");
    return true;
  }

  return false;
}

Module({
  command: "goodnight",
  alias: ["gn", "gcof", "groupclose", "close"],
  package: "group",
  description: "Send custom refresh message and auto-close group with Normal or Funny Good Night card.",
})(async (message, match) => {
  const quoted = message?.raw || message;

  try {
    if (!message?.isGroup) {
      return sendTextMessage(
        message,
        theme?.isGroup || "❌ Ei command shudhu group-er jonno proyojjo!",
        quoted
      );
    }

    await message.loadGroupInfo?.();

    if (!message?.isAdmin && !message?.isFromMe && !message?.isfromMe) {
      return sendTextMessage(
        message,
        theme?.isAdmin || "⚠️ Ei command use korte hole admin hote hobe!",
        quoted
      );
    }

    if (message?.isBotAdmin === false) {
      return sendTextMessage(
        message,
        theme?.isBotAdmin || "⚠️ Group close korar jonno bot-ke admin korte hobe!",
        quoted
      );
    }

    const mode = String(match || "").trim().split(/\s+/)[0]?.toLowerCase();
    const isFunny = mode === "funny" || mode === "fun";

    // 1. প্রথমে Refresh Message পাঠানো
    await sendTextMessage(
      message,
      isFunny ? REFRESH_FUNNY : REFRESH_NORMAL,
      quoted
    );

    // 2. ১.৫ সেকেন্ড অপেক্ষা করা
    await new Promise((resolve) => setTimeout(resolve, 1500));

    // 3. গ্রুপ ক্লোজ করা
    try {
      await closeGroupChat(message);
    } catch (err) {
      console.error("Group settings update error:", err);
    }

    // 4. মূল Good Night কার্ড পাঠানো
    await sendTextMessage(
      message,
      isFunny ? FUNNY_CARD : NORMAL_CARD,
      null
    );
  } catch (e) {
    console.error("Goodnight Command Error:", e);
    await sendTextMessage(message, "❌ Kono ekta error hoyeche!", quoted);
  }
});
